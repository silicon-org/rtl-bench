#!/usr/bin/env python3
"""Copy the files of the Taxi variants from a checkout of upstream and write their file lists.

usage: vendor.py <taxi checkout> <design directory>

The file lists are resolved the way the Makefiles of the tests of upstream do (`process_f_files` and `uniq_base`):
the list files (`.f`) are expanded in place, and of the files with the same name the last one stays. Nothing is
edited: every file is a copy at the same relative path under `src/taxi/`, and symbolic links of upstream stay
symbolic links.
"""

import os
import shutil
import sys

# variant id: (the VERILOG_SOURCES of the Makefile of the test of upstream, in its order; directory of the test;
#              files of that directory to copy)
VARIANTS = {
    "eth_phy_10g": (
        ["src/eth/rtl/taxi_eth_phy_10g.f"],
        "src/eth/tb/taxi_eth_phy_10g",
        ["Makefile", "test_taxi_eth_phy_10g.py", "baser.py"],
    ),
    "kc705_gmii": (
        [
            "src/eth/example/KC705/fpga/rtl/fpga_core.sv",
            "src/eth/rtl/taxi_eth_mac_1g_fifo.f",
            "src/eth/rtl/taxi_eth_mac_1g_gmii_fifo.f",
            "src/eth/rtl/taxi_eth_mac_1g_rgmii_fifo.f",
            "src/xfcp/rtl/taxi_xfcp_if_uart.f",
            "src/xfcp/rtl/taxi_xfcp_switch.sv",
            "src/xfcp/rtl/taxi_xfcp_mod_i2c_master.f",
            "src/xfcp/rtl/taxi_xfcp_mod_stats.f",
            "src/sync/rtl/taxi_sync_reset.sv",
            "src/sync/rtl/taxi_sync_signal.sv",
            "src/io/rtl/taxi_debounce_switch.sv",
        ],
        "src/eth/example/KC705/fpga/tb/fpga_core",
        ["Makefile", "test_fpga_core.py"],
    ),
}

TOP_FILES = ["LICENSE", "AUTHORS"]


def expand(root, path, lists):
    """The source files of a path; list files are expanded and recorded."""
    if not path.endswith(".f"):
        return [path]
    lists.add(path)
    out = []
    base = os.path.dirname(os.path.join(root, path))
    for word in open(os.path.join(root, path)).read().split():
        real = os.path.realpath(os.path.join(base, word))
        out += expand(root, os.path.relpath(real, os.path.realpath(root)), lists)
    return out


def uniq_base(files):
    """Of the files with one name, the last stays, in the order of the last ones (as the Makefiles do)."""
    seen, out = set(), []
    for f in reversed(files):
        name = os.path.basename(f)
        if name not in seen:
            seen.add(name)
            out.append(f)
    return out[::-1]


def copy(root, dest, rel):
    src = os.path.join(root, rel)
    dst = os.path.join(dest, "src/taxi", rel)
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    if os.path.lexists(dst):
        os.remove(dst)
    if os.path.islink(src):
        target = os.readlink(src)
        os.symlink(target, dst)
        # the target of the link is a copy too
        real = os.path.relpath(os.path.realpath(src), os.path.realpath(root))
        copy(root, dest, real)
    else:
        shutil.copy2(src, dst)


def main():
    root, dest = sys.argv[1], sys.argv[2]
    shutil.rmtree(os.path.join(dest, "src"), ignore_errors=True)
    all_lists, all_files, support = set(), set(), []
    for vid, (roots, testdir, testfiles) in VARIANTS.items():
        lists = set()
        files = []
        for r in roots:
            files += expand(root, r, lists)
        files = uniq_base(files)
        all_lists |= lists
        all_files |= set(files)
        vdir = os.path.join(dest, "variants", vid)
        os.makedirs(vdir, exist_ok=True)
        with open(os.path.join(vdir, "synth.f"), "w") as f:
            f.write(f"# the VERILOG_SOURCES of {testdir}/Makefile, resolved by recipe/vendor.py\n")
            for p in files:
                f.write(f"src/taxi/{p}\n")
        with open(os.path.join(vdir, "sim.f"), "w") as f:
            f.write("# no testbench files: the tests of upstream are cocotb Python (sim.cocotb)\n")
        for t in testfiles:
            all_files.add(f"{testdir}/{t}")
            if t == "baser.py":
                support.append(f"src/taxi/{testdir}/{t}")
    for rel in sorted(all_files | all_lists):
        copy(root, dest, rel)
    for t in TOP_FILES:
        copy(root, dest, t)
    # the targets of links
    for dirpath, _, names in os.walk(os.path.join(dest, "src")):
        for n in names:
            p = os.path.join(dirpath, n)
            if os.path.islink(p):
                support.append(os.path.relpath(os.path.realpath(p), dest))
    os.makedirs(os.path.join(dest, "recipe"), exist_ok=True)
    # unused.txt: files under src/ that no view lists
    print("support:", sorted(set(support)))
    with open(os.path.join(dest, "recipe/unused.txt"), "w") as f:
        f.write("# generated by recipe/vendor.py\n")
        for rel in sorted(all_lists):
            f.write(f"src/taxi/{rel} file list of upstream, resolved into variants/*/synth.f\n")
        for vid, (_, testdir, testfiles) in VARIANTS.items():
            if "Makefile" in testfiles:
                f.write(f"src/taxi/{testdir}/Makefile makefile of the upstream test of {vid}: the parameters and files of its build\n")
        f.write("src/taxi/AUTHORS authors of upstream\n")


if __name__ == "__main__":
    main()
