//! SDC generated from the clock and constraints tables of a variant.

use crate::schema::Variant;

/// Periods are written in ns, the SDC default unit.
fn ns(ps: f64) -> String {
    let s = format!("{:.3}", ps / 1000.0);
    s.trim_end_matches('0').trim_end_matches('.').to_string()
}

pub fn generate(full_id: &str, v: &Variant, technology: &str) -> Result<String, String> {
    let c = &v.constraints;
    let first = v.clock.first().ok_or("the variant has no clock")?;
    let mut out = format!("# {full_id}, technology {technology}, generated by rtl-bench sdc\n");
    let mut periods = Vec::new();
    for clk in &v.clock {
        if clk.period_ps.is_empty() {
            return Err(format!(
                "clock `{}` has no period: period_ps is not set for any technology",
                clk.name
            ));
        }
        let p = *clk.period_ps.get(technology).ok_or_else(|| {
            let known: Vec<&str> = clk.period_ps.keys().map(String::as_str).collect();
            format!(
                "clock `{}` has no period for technology `{technology}` (has: {})",
                clk.name,
                known.join(", ")
            )
        })?;
        out += &format!("# clock {}: {}\n", clk.name, clk.source);
        periods.push(p as f64);
    }
    let (Some(fin), Some(fout)) = (c.input_delay_fraction, c.output_delay_fraction) else {
        return Err("input_delay_fraction and output_delay_fraction are not set".to_string());
    };
    out += &format!("# I/O delays: {}\n", c.source);
    for f in &c.sdc {
        out += &format!("# upstream SDC, not applied here: {f}\n");
    }
    for (clk, p) in v.clock.iter().zip(&periods) {
        out += &format!(
            "create_clock -name {} -period {} [get_ports {}]\n",
            clk.name,
            ns(*p),
            clk.port
        );
    }
    // The first clock launches the inputs and captures the outputs.
    let mut skip: Vec<&str> = v.clock.iter().map(|k| k.port.as_str()).collect();
    skip.extend(c.resets.iter().map(String::as_str));
    out += &format!(
        "set_input_delay {} -clock {} [remove_from_collection [all_inputs] [get_ports {{{}}}]]\n",
        ns(fin * periods[0]),
        first.name,
        skip.join(" ")
    );
    out += &format!(
        "set_output_delay {} -clock {} [all_outputs]\n",
        ns(fout * periods[0]),
        first.name
    );
    for p in &c.false_paths {
        out += "set_false_path";
        if let Some(from) = &p.from {
            out += &format!(" -from [get_ports {from}]");
        }
        if let Some(to) = &p.to {
            out += &format!(" -to [get_ports {to}]");
        }
        out += "\n";
    }
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::schema::DesignFile;

    fn variant(period: u64, frac: f64) -> Variant {
        let text = format!(
            r#"
[design]
id = "d"
name = "D"
description = "d"
[source]
repository = "https://example.org/d"
commit = "0123456789abcdef0123456789abcdef01234567"
mode = "reference"
licence = "MIT"
[[variant]]
id = "v"
description = "d"
[variant.synth]
top = "t"
language = "sv-2017"
files = "s.f"
[[variant.clock]]
name = "clk"
port = "clk_i"
period_ps = {{ tech = {period} }}
source = "s"
[variant.constraints]
input_delay_fraction = {frac}
output_delay_fraction = 0.0
source = "s"
resets = ["rst_i"]
false_paths = [{{ from = "rst_i" }}]
sdc = ["constraints/up.sdc"]
[variant.sim]
simulator = "verilator"
top = "tb"
files = "t.f"
dut = "tb.dut"
"#
        );
        toml::from_str::<DesignFile>(&text)
            .unwrap()
            .variant
            .remove(0)
    }

    #[test]
    fn writes_clock_delays_and_false_paths() {
        let s = generate("d.v", &variant(1087, 0.2), "tech").unwrap();
        assert!(
            s.contains("create_clock -name clk -period 1.087 [get_ports clk_i]\n"),
            "{s}"
        );
        assert!(s.contains("set_input_delay 0.217 -clock clk [remove_from_collection [all_inputs] [get_ports {clk_i rst_i}]]\n"), "{s}");
        assert!(
            s.contains("set_output_delay 0 -clock clk [all_outputs]\n"),
            "{s}"
        );
        assert!(
            s.contains("set_false_path -from [get_ports rst_i]\n"),
            "{s}"
        );
        assert!(
            s.contains("# upstream SDC, not applied here: constraints/up.sdc"),
            "{s}"
        );
    }

    #[test]
    fn unknown_technology_lists_the_known_ones() {
        let err = generate("d.v", &variant(1000, 0.2), "other").unwrap_err();
        assert!(
            err.contains("no period for technology `other`") && err.contains("has: tech"),
            "{err}"
        );
    }

    #[test]
    fn clock_without_period_is_an_error() {
        let mut v = variant(1000, 0.2);
        v.clock[0].period_ps.clear();
        let err = generate("d.v", &v, "tech").unwrap_err();
        assert!(
            err.contains("clock `clk` has no period") && err.contains("not set"),
            "{err}"
        );
    }

    #[test]
    fn missing_delay_fractions_are_an_error() {
        let mut v = variant(1000, 0.2);
        v.constraints.input_delay_fraction = None;
        let err = generate("d.v", &v, "tech").unwrap_err();
        assert!(
            err.contains("delay_fraction") && err.contains("not set"),
            "{err}"
        );
    }

    #[test]
    fn whole_nanoseconds_have_no_trailing_zeros() {
        assert_eq!(ns(10000.0), "10");
        assert_eq!(ns(1500.0), "1.5");
    }
}
